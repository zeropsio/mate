import * as NodeServices from "@effect/platform-node/NodeServices";
import { assert, describe, it } from "@effect/vitest";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Path from "effect/Path";
import * as Schema from "effect/Schema";

import { CSS_KIND, type ExceptionEntry } from "@t3tools/oxlint-plugin-t3code/exceptions";

import {
  checkCssTokens,
  checkOffScaleBudget,
  countOffScaleDeclarations,
  offScaleProperty,
  reconcileCssTokenFindings,
  scanCssSource,
} from "./check-css-tokens.ts";

const scan = (source: string) => scanCssSource({ path: "apps/web/src/fixture.css", source });
const encodeUnknownJson = Schema.encodeUnknownSync(Schema.fromJsonString(Schema.Unknown));

describe("CSS token scanning", () => {
  it("exempts theme-source custom properties", () => {
    const source = `
      :root { --color-x: #fff; }
      @layer base { :root { --stage-x: oklch(0.5 0.1 200); } }
      html[data-theme-id="x"] { --app-theme-x: #fff; }
      :is(html[data-theme-id="a"], html[data-theme-id="b"]) { --pair: #fff; }
      @theme { --framework-x: rgb(0 0 0); }
      @layer theme { .scope { --mobile-x: hsl(0 0% 0%); } }
    `;

    assert.deepStrictEqual(scan(source), []);
  });

  it("fingerprints ad-hoc declarations with their selector", () => {
    assert.deepStrictEqual(scan(`.card { background: rgb(0 0 0 / 5%); }`), [
      {
        path: "apps/web/src/fixture.css",
        kind: CSS_KIND,
        fingerprint: ".card{background:rgb(0 0 0 / 5%)}",
      },
    ]);
  });

  it("does not treat color-space names in color-mix as literals", () => {
    assert.deepStrictEqual(scan(`.card { color: color-mix(in oklch, var(--x) 80%, black); }`), []);
  });

  it("finds custom properties outside palette ancestors", () => {
    assert.deepStrictEqual(scan(`@utility x { --y: #000; }`), [
      {
        path: "apps/web/src/fixture.css",
        kind: CSS_KIND,
        fingerprint: "@utility x{--y:#000}",
      },
    ]);
  });

  it("keeps the ancestor stack aligned across an empty block header", () => {
    assert.deepStrictEqual(scan(`.outer { { } .card { color: #fff; } }`), [
      {
        path: "apps/web/src/fixture.css",
        kind: CSS_KIND,
        fingerprint: ".outer > .card{color:#fff}",
      },
    ]);
  });

  it("does not exempt a descendant selector that merely contains a theme-id block", () => {
    assert.deepStrictEqual(scan(`html[data-theme-id="x"] .card { --composer-glass: #fff; }`), [
      {
        path: "apps/web/src/fixture.css",
        kind: CSS_KIND,
        fingerprint: 'html[data-theme-id="x"] .card{--composer-glass:#fff}',
      },
    ]);
  });

  it("does not exempt negated root selectors", () => {
    assert.deepStrictEqual(scan(`body:not(:root) { --x: #fff; }`), [
      {
        path: "apps/web/src/fixture.css",
        kind: CSS_KIND,
        fingerprint: "body:not(:root){--x:#fff}",
      },
    ]);
  });

  it("excludes URL fragments before matching raw colours", () => {
    assert.deepStrictEqual(scan(`.icon { mask: url(#abcdef); }`), []);
  });

  it("skips generated files by their first line", () => {
    assert.deepStrictEqual(
      scan(`/* Generated by scripts/example.ts. Do not edit manually. */\n.x { color: #fff; }`),
      [],
    );
  });
});

describe("the scale in hand-written CSS", () => {
  it.each([
    ["font-size", "14px", undefined],
    ["font-size", "0.75rem", undefined],
    ["font-size", "13px", "font-size"],
    ["font-size", "0.86em", undefined],
    ["font-size", "var(--text-line)", undefined],
    ["border-radius", "8px", undefined],
    ["border-radius", "12px 12px 0 0", undefined],
    ["border-radius", "9999px", undefined],
    ["border-radius", "50%", undefined],
    ["border-radius", "10px", "border-radius"],
    ["border-top-left-radius", "6px", "border-radius"],
    ["transition", "opacity 150ms var(--ease-out-strong)", undefined],
    ["transition", "opacity 200ms ease, transform 260ms ease", undefined],
    ["transition", "opacity 120ms ease", "duration"],
    ["transition", "opacity 150ms ease 40ms", undefined],
    ["transition-duration", "180ms", "duration"],
    ["animation", "status-pulse 2s infinite", undefined],
    ["animation", "blink 600ms infinite", undefined],
    ["animation", "panel-in 420ms ease backwards", "duration"],
    ["color", "13px", undefined],
  ] as const)("reads %s: %s as %s", (property, value, expected) => {
    assert.strictEqual(offScaleProperty(property, value), expected);
  });

  it("counts declarations between the steps and leaves custom properties to the theme", () => {
    assert.deepStrictEqual(
      countOffScaleDeclarations(`
        :root { --radius-x: 10px; }
        .a { font-size: 13px; border-radius: 10px; }
        .b { font-size: 12px; transition: opacity 120ms ease; }
      `),
      { "font-size": 1, "border-radius": 1, duration: 1 },
    );
  });

  it("refuses a web stylesheet that adds a value between the steps and ignores other clients", () => {
    const budget = { "font-size": 1, "border-radius": 0, duration: 0 } as const;
    const within = checkOffScaleBudget(
      [{ path: "apps/web/src/a.css", source: ".a { font-size: 13px; }" }],
      budget,
    );
    assert.deepStrictEqual(within.messages, []);
    const over = checkOffScaleBudget(
      [
        { path: "apps/web/src/a.css", source: ".a { font-size: 13px; }" },
        { path: "apps/web/src/b.css", source: ".b { font-size: 11px; }" },
        { path: "apps/mobile/global.css", source: ".c { border-radius: 10px; }" },
      ],
      budget,
    );
    assert.strictEqual(over.messages.length, 1);
    assert.match(over.messages[0]!, /^2 font-size declarations/u);
  });
});

it.layer(NodeServices.layer)("CSS ledger reconciliation", (it) => {
  it.effect("skips a dangling CSS symlink with a warning", () =>
    Effect.scoped(
      Effect.gen(function* () {
        const fs = yield* FileSystem.FileSystem;
        const path = yield* Path.Path;
        const repoRoot = yield* fs.makeTempDirectoryScoped({ prefix: "css-token-walk-" });
        const sourceDirectory = path.join(repoRoot, "apps/web/src/nested");
        yield* fs.makeDirectory(sourceDirectory, { recursive: true });
        yield* fs.symlink(
          path.join(repoRoot, "missing.css"),
          path.join(sourceDirectory, "dangling.css"),
        );

        const warnings: Array<string> = [];
        const result = yield* checkCssTokens({
          cwd: repoRoot,
          directory: path.join(repoRoot, "exceptions"),
          warn: (warning) => warnings.push(warning),
        });

        assert.equal(result.exitCode, 0);
        assert.deepStrictEqual(warnings, [
          "CSS source scan: skipped unreadable entry apps/web/src/nested/dangling.css",
        ]);
      }),
    ),
  );

  it.effect("returns a non-zero result naming an unlisted finding", () =>
    Effect.scoped(
      Effect.gen(function* () {
        const fs = yield* FileSystem.FileSystem;
        const path = yield* Path.Path;
        const directory = yield* fs.makeTempDirectoryScoped({ prefix: "css-token-ledger-" });
        const ledgered = scan(`.one { color: #fff; }`)[0]!;
        const unlisted = scan(`.two { background: rgb(0 0 0); }`)[0]!;
        const entry: ExceptionEntry = {
          ...ledgered,
          owner: "karel",
          reason: "fixture exception",
          expires: "never",
        };
        yield* fs.writeFileString(
          path.join(directory, "no-theme-escape-hatches.json"),
          `${encodeUnknownJson([entry])}\n`,
        );

        const result = reconcileCssTokenFindings({
          directory,
          findings: [ledgered, unlisted],
        });

        assert.equal(result.exitCode, 1);
        assert.equal(result.problemCount, 1);
        assert.include(result.report, "unlisted apps/web/src/fixture.css:css-declaration");
        assert.include(result.report, unlisted.fingerprint);
      }),
    ),
  );
});
